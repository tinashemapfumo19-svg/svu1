import { test, expect } from '@playwright/test';
import { readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import pg from 'pg';

test.skip(!process.env.DATABASE_URL || !/^\/svu_rebuild_it_\d+$/.test(new URL(process.env.DATABASE_URL).pathname),'Leave journeys require the isolated integration database.');
test('staff leave reserves balances and separates recommendation from approval',async ({page,request},info) => {
  test.setTimeout(240000);
  page.setDefaultTimeout(15000);
  const suffix = `${info.project.name}_${Date.now()}`,categoryCode=`LV_${Date.now()}`;
  const year = new Date().getUTCFullYear()+1;
  let monday = new Date(Date.UTC(year,0,4));
  while (monday.getUTCDay()!==1) monday=new Date(monday.getTime()+86400000);
  const day = (n) => new Date(monday.getTime()+n*86400000).toISOString().slice(0,10);
  const api = async (method,path,data,token,status=200) => {
    const response=await request.fetch(path,{method,data,maxRetries:method==='GET' ? 2 : 0,headers:token ? {Authorization:`Bearer ${token}`} : {}});
    expect(response.status(),`${method} ${path}: ${await response.text()}`).toBe(status);
    return (await response.json()).data;
  };
  const admin=await api('POST','/api/identity/sessions',{email:'admin@southvalley.test',password:'Phase1-Admin-Password-2026!'},null,201);
  const student=await api('POST','/api/identity/sessions',{email:'tinashe@example.edu',password:'Phase1-Student-Password-2026!'},null,201);
  const supervisor=await staff('Supervisor','hr_officer');
  const employee=await staff('Employee','lecturer',supervisor.staffId);
  const outsider=await staff('Outsider','lecturer');
  await api('POST','/api/access/role-assignments',{accountId:outsider.accountId,roleCode:'hr_officer',scope:{programmeCodes:['BSC-IS']},reason:'Scoped HR fixture'},admin.token,201);
  await api('POST','/api/staff-leave/categories',{code:'BAD_SCOPED',name:'Bad',dayBasis:'calendar',reason:'Not global'},outsider.token,403);
  await api('GET','/api/staff-leave',undefined,student.token,403);
  await open(admin);
  await page.getByText('Categories and counting policy',{exact:true}).click();
  const policy=page.locator('[data-leave-category]');
  await policy.locator('[data-leave-add-date]').click();
  await policy.locator('[aria-label="Excluded date"]').fill(day(1));
  await submit(policy,{code:categoryCode,name:`Annual leave ${suffix}`,dayBasis:'weekdays',reason:'Approved counting policy fixture'});
  await expect(page.getByRole('status')).toHaveText('Leave category created.');
  await api('POST','/api/staff-leave/categories',{code:categoryCode,name:'Duplicate',dayBasis:'calendar',reason:'Duplicate'},admin.token,409);
  await submit(page.locator('[data-leave-filter]'),{year});
  await expect(page.locator('[data-leave-filter] [name=year]')).toHaveValue(String(year));
  await page.getByText('Balance ledger',{exact:true}).click();
  await submit(page.locator('[data-leave-balance]'),{staffId:employee.staffId,categoryCode,days:5,reason:'Confirmed annual entitlement'});
  await expect(page.getByRole('status')).toHaveText('Leave balance entry recorded.');
  await api('POST','/api/staff-leave/balances',{staffId:supervisor.staffId,categoryCode,year,days:5,reason:'Self grant'},supervisor.token,403);
  await open(employee);
  await submit(page.locator('[data-leave-filter]'),{year});
  await page.getByText('Request leave',{exact:true}).click();
  await submit(page.locator('[data-leave-new]'),{categoryCode,startsOn:day(0),endsOn:day(1),reason:'Annual rest'});
  await expect(page.getByRole('status')).toHaveText('Leave request submitted.');
  let row=(await api('GET',`/api/staff-leave?year=${year}`,undefined,employee.token)).items[0];
  expect(row).toMatchObject({days:1,status:'requested',actions:['cancel']});
  expect((await api('GET',`/api/staff-leave?${new URLSearchParams({year,staffQ:`Employee ${suffix}`})}`,undefined,admin.token)).items.map((r) => r.id)).toEqual([row.id]);
  expect((await api('GET',`/api/staff-leave?${new URLSearchParams({year,staffQ:'Not an employee 99999'})}`,undefined,admin.token)).total).toBe(0);
  let b=await balance(employee);
  expect(b).toMatchObject({granted:5,reserved:1,used:0,available:4});
  await api('GET',`/api/staff-leave/requests/${row.id}`,undefined,outsider.token,404);
  await api('GET',`/api/staff-leave/balances?staffId=${employee.staffId}&categoryCode=${categoryCode}&year=${year}`,undefined,outsider.token,404);
  await decision(row,'approve',admin,403);
  await decision(row,'recommend',employee,403);
  await api('POST','/api/staff-leave',{categoryCode,startsOn:day(0),endsOn:day(0),reason:'Overlap',replayKey:randomUUID()},employee.token,409);
  await open(supervisor);
  await submit(page.locator('[data-leave-filter]'),{year});
  await page.locator(`[data-leave-detail="${row.id}"]`).click();
  await submit(page.locator('[data-leave-decision]'),{action:'recommend',reason:'Cover arranged'});
  await expect(page.getByRole('status')).toHaveText('Leave decision recorded.');
  row=await api('GET',`/api/staff-leave/requests/${row.id}`,undefined,supervisor.token);
  expect(row).toMatchObject({status:'recommended',revision:2});
  expect(row.actions).not.toContain('approve');
  await decision(row,'approve',supervisor,403);
  await decision({...row,revision:1},'approve',admin,409);
  await open(admin);
  await submit(page.locator('[data-leave-filter]'),{year});
  await page.locator(`[data-leave-detail="${row.id}"]`).click();
  await submit(page.locator('[data-leave-decision]'),{action:'approve',reason:'Independent HR approval'});
  await expect(page.locator('[data-leave-status]')).toHaveText('approved');
  row=await api('GET',`/api/staff-leave/requests/${row.id}`,undefined,admin.token);
  expect(row.history.map((h) => h.toStatus)).toEqual(['requested','recommended','approved']);
  expect(await balance(employee)).toMatchObject({reserved:0,used:1,available:4});
  await page.evaluate(async () => {document.activeElement?.blur();window.scrollTo({top:0,behavior:'instant'});await new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));});
  const statusBounds=await page.locator('[data-leave-status]').boundingBox();
  expect(statusBounds.width).toBeGreaterThan(45);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize().width);
  await page.screenshot({path:info.outputPath('approved-leave.png'),fullPage:true});
  await open(employee);
  await submit(page.locator('[data-leave-filter]'),{year});
  await page.locator(`[data-leave-detail="${row.id}"]`).click();
  await submit(page.locator('[data-leave-decision]'),{action:'cancel',reason:'Trip cancelled before leave begins'});
  await expect(page.locator('[data-leave-status]')).toHaveText('cancelled');
  expect(await balance(employee)).toMatchObject({reserved:0,used:0,available:5});
  const payload={categoryCode,startsOn:day(7),endsOn:day(9),reason:'Second request',replayKey:randomUUID()};
  row=await api('POST','/api/staff-leave',payload,employee.token,201);
  const replay=await api('POST','/api/staff-leave',Object.fromEntries(Object.entries(payload).reverse()),employee.token,201);
  expect(replay.id).toBe(row.id);
  await api('POST','/api/staff-leave',{...payload,reason:'Changed replay'},employee.token,409);
  await api('POST','/api/staff-leave/balances',{staffId:employee.staffId,categoryCode,year,days:-3,reason:'Would overdraw reserved days'},admin.token,409);
  row=await decision(row,'recommend',supervisor);
  row=await decision(row,'approve',admin);
  row=await decision(row,'reverse',admin);
  expect(row.status).toBe('reversed');
  expect(await balance(employee)).toMatchObject({used:0,available:5});
  const candidates=[14,21].map((n) => ({categoryCode,startsOn:day(n),endsOn:day(n+2),reason:'Concurrent booking',replayKey:randomUUID()}));
  const responses=await Promise.all(candidates.map((data) => request.post('/api/staff-leave',{data,headers:{Authorization:`Bearer ${employee.token}`}})));
  expect(responses.map((r) => r.status()).sort()).toEqual([201,409]);
  const winner=(await responses.find((r) => r.status()===201).json()).data;
  await decision(winner,'deny',supervisor);
  expect(await balance(employee)).toMatchObject({reserved:0,available:5});
  let reassigned=await api('POST','/api/staff-leave',{categoryCode,startsOn:day(28),endsOn:day(28),reason:'Reporting line change',replayKey:randomUUID()},employee.token,201);
  const employment=await api('GET',`/api/staff/${employee.staffId}`,undefined,admin.token);
  await api('POST',`/api/staff/${employee.staffId}/employment`,{revision:employment.revision,departmentId:'dept_computing',category:'LECTURER',grade:'L1',supervisorStaffId:outsider.staffId,effectiveFrom:new Date().toISOString().slice(0,10),reason:'Reassign current supervisor'},admin.token);
  await decision(reassigned,'recommend',supervisor,403);
  reassigned=await decision(reassigned,'recommend',outsider);
  expect(reassigned.status).toBe('recommended');
  await decision(reassigned,'cancel',employee);
  expect(await balance(employee)).toMatchObject({reserved:0,available:5});
  const category=(await api('GET','/api/staff-leave',undefined,admin.token)).categories.find((c) => c.code===categoryCode);
  await api('PUT',`/api/staff-leave/categories/${categoryCode}`,{revision:category.revision,active:false,reason:'Retired category'},admin.token);
  await api('PUT',`/api/staff-leave/categories/${categoryCode}`,{revision:category.revision,active:true,reason:'Stale'},admin.token,409);
  await api('POST','/api/staff-leave',{categoryCode,startsOn:day(28),endsOn:day(28),reason:'Inactive',replayKey:randomUUID()},employee.token,400);
  const db=new pg.Client({connectionString:process.env.DATABASE_URL});
  await db.connect();
  try {
    await expect(db.query('update staff_leave_requests set days=100 where id=$1',[row.id])).rejects.toThrow('immutable');
    await expect(db.query('delete from staff_leave_history where request_id=$1',[row.id])).rejects.toThrow();
    await expect(db.query('update staff_leave_balance_entries set days=100 where staff_id=$1',[employee.staffId])).rejects.toThrow();
    await expect(db.query("update staff_leave_categories set day_basis='calendar' where code=$1",[categoryCode])).rejects.toThrow('immutable');
  } finally {await db.end();}
  const events=await api('GET',`/api/audit/events?subjectId=${row.id}`,undefined,admin.token);
  expect(events.map((e) => e.action)).toEqual(expect.arrayContaining(['staff.leave.requested','staff.leave.recommended','staff.leave.approved','staff.leave.reversed']));

  async function decision(r,action,actor,status=200) {return api('POST',`/api/staff-leave/requests/${r.id}/${action}`,{revision:r.revision,reason:`${action} fixture`},actor.token,status);}
  async function balance(actor) {return api('GET',`/api/staff-leave/balances?staffId=${actor.staffId}&categoryCode=${categoryCode}&year=${year}`,undefined,actor.token);}
  async function open(actor) {await page.goto('/');await page.evaluate((session) => window.svuSession.set(session),actor);await page.goto('/#registry/leave');await expect(page.locator('.staff-leave')).toBeVisible();await expect(page.locator('.review-controls')).toBeEnabled();}
  async function submit(form,values) {for (const [name,value] of Object.entries(values)) {const input=form.locator(`[name="${name}"]`);if (await input.evaluate((n) => n.tagName==='SELECT')) await input.selectOption(String(value));else await input.fill(String(value));}await form.locator('button[type=submit]').click();await expect(page.locator('.review-controls')).toBeEnabled();}
  async function staff(label,roleCode,supervisorStaffId) {
    const email=`leave.${label.toLowerCase()}.${suffix}@example.edu`,password='Kariba-Leave-Staff-2026!';
    const record=await api('POST','/api/staff',{email,legalName:`${label} ${suffix}`,preferredName:label,category:'LECTURER',grade:'L1',departmentId:'dept_computing',roleCode,engagedOn:'2026-01-01',...(supervisorStaffId ? {supervisorStaffId} : {}),reason:'Leave journey fixture'},admin.token,201);
    const messages=await Promise.all((await readdir(process.env.SVU_DEV_OUTBOX)).map(async (f) => JSON.parse(await readFile(join(process.env.SVU_DEV_OUTBOX,f),'utf8'))));
    const token=messages.find((m) => m.recipientEmail===email).variables.activationToken;
    await api('POST','/api/identity/activations',{token,password,preferredName:label,legalName:`${label} ${suffix}`});
    const session=await api('POST','/api/identity/sessions',{email,password},null,201);
    const me=await api('GET','/api/identity/me',undefined,session.token);
    return {...session,staffId:record.id,accountId:me.account.id};
  }
});
